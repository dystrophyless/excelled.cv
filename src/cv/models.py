"""The student's CV (006 data-model.md): one row per profile, metadata and content together."""

import enum
import uuid
from datetime import UTC, datetime

from sqlalchemy import CheckConstraint, DateTime, Enum, ForeignKey, LargeBinary, String
from sqlalchemy.orm import Mapped, deferred, mapped_column

from src.database import Base

MAX_BYTES = 5 * 1024 * 1024


class CvFormat(enum.StrEnum):
    pdf = "pdf"
    docx = "docx"


class StudentCv(Base):
    __tablename__ = "student_cvs"
    __table_args__ = (
        CheckConstraint(f"size_bytes BETWEEN 1 AND {MAX_BYTES}", name="ck_student_cvs_size"),
        CheckConstraint("octet_length(content) = size_bytes", name="ck_student_cvs_content_size"),
    )

    # Generated by the application and changed on every replacement (research R5).
    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    profile_id: Mapped[int] = mapped_column(ForeignKey("student_profiles.id", ondelete="CASCADE"), unique=True)
    file_name: Mapped[str] = mapped_column(String(150))
    format: Mapped[CvFormat] = mapped_column(Enum(CvFormat, name="cv_format"))
    size_bytes: Mapped[int]
    # Never loaded by accident: only the download asks for it (`undefer`); any other access raises.
    content: Mapped[bytes] = deferred(mapped_column(LargeBinary), raiseload=True)
    uploaded_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(UTC))
